function voiceBoundary(author, synthesis, inference) {
	return `  作者原意：${author}\n\n  跨书综合：${synthesis}\n\n  系统推论：${inference}`;
}

function modelBody({ core, components, chain, boundary, voice }) {
	return `## 核心思想\n\n<!-- unit: claim-core -->\n\n  ${core}\n\n## 关键组件\n\n<!-- unit: mechanism-components -->\n\n${components.map((item) => `- ${item}`).join("\n")}\n\n## 结构关系或因果链条\n\n<!-- unit: mechanism-structure -->\n\n  ${chain}\n\n## 失效边界\n\n<!-- unit: boundary-primary -->\n\n  ${boundary}\n\n## 来源与证据边界\n\n${voiceBoundary(...voice)}`;
}

function methodBody({ input, steps, output, boundary, voice }) {
	return `## 输入\n\n<!-- unit: condition-input -->\n\n${input.map((item) => `- ${item}`).join("\n")}\n\n## 步骤\n\n<!-- unit: mechanism-procedure -->\n\n${steps.map((item, index) => `${index + 1}. ${item}`).join("\n")}\n\n## 输出\n\n<!-- unit: claim-output -->\n\n  ${output}\n\n## 适用边界\n\n<!-- unit: boundary-primary -->\n\n  ${boundary}\n\n## 来源与证据边界\n\n${voiceBoundary(...voice)}`;
}

function phenomenonBody({ interpretation, pattern, examples, boundary, voice }) {
	return `## 诠释\n\n  ${interpretation}\n\n## 模式描述\n\n<!-- unit: claim-pattern -->\n\n  ${pattern}\n\n## 典型实例\n\n<!-- unit: evidence-cases -->\n\n${examples.map((item) => `- ${item}`).join("\n")}\n\n## 反例与失效条件\n\n<!-- unit: boundary-primary -->\n\n  ${boundary}\n\n## 来源与证据边界\n\n${voiceBoundary(...voice)}`;
}

