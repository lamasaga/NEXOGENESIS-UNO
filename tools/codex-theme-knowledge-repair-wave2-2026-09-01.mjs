function body({ claim, parts, chain, boundary, author, synthesis, inference }) {
	return `## 核心思想\n\n<!-- unit: claim-core -->\n\n  ${claim}\n\n## 关键组件\n\n<!-- unit: mechanism-components -->\n\n${parts.map((x) => `- ${x}`).join("\n")}\n\n## 结构关系或因果链条\n\n<!-- unit: mechanism-structure -->\n\n  ${chain}\n\n## 失效边界\n\n<!-- unit: boundary-primary -->\n\n  ${boundary}\n\n## 来源与证据边界\n\n  作者原意：${author}\n\n  跨书综合：${synthesis}\n\n  系统推论：${inference}`;
}

function methodBody({ claim, parts, chain, boundary, author, synthesis, inference }) {
	return `## 输入\n\n<!-- unit: condition-input -->\n\n${parts.map((x) => `- ${x}`).join("\n")}\n\n## 步骤\n\n<!-- unit: mechanism-procedure -->\n\n  ${chain}\n\n## 输出\n\n<!-- unit: claim-output -->\n\n  ${claim}\n\n## 适用边界\n\n<!-- unit: boundary-primary -->\n\n  ${boundary}\n\n## 来源与证据边界\n\n  作者原意：${author}\n\n  跨书综合：${synthesis}\n\n  系统推论：${inference}`;
}

function card({ id, type = "model", domains, sources, relations, school, scope, ...text }) {
	return {
		id, title: id, type, maturity: "growing", lifecycle: "active", domains,
		origin: "document", school, applicable_scope: scope, theory_status: "provisional",
		sources, relations, body: type === "method" ? methodBody(text) : body(text), created: today, updated: today
	};
}

